/**
 * Optional: replace the bundled SVG artwork with free Pixabay photos.
 *
 * 1. Copy .env.example to .env and set PIXABAY_API_KEY=your_key
 * 2. npm run images:fetch
 *
 * Downloaded photos are resized to a maximum width/height of 1200px with sharp,
 * saved under public/images/products/, credited in public/images/CREDITS.md and
 * mapped in src/data/imageMap.ts. Missing results are reported, never invented.
 * No API key? The script exits cleanly and the SVG artwork stays in place.
 */
import 'dotenv/config';
import { readdirSync, readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const apiKey = process.env.PIXABAY_API_KEY?.trim();
const productsDir = join(root, 'src', 'data', 'products');
const outputDir = join(root, 'public', 'images', 'products');
const mapPath = join(root, 'src', 'data', 'imageMap.ts');
const creditsPath = join(root, 'public', 'images', 'CREDITS.md');
const API = 'https://pixabay.com/api/';

if (!apiKey) {
  console.warn('PIXABAY_API_KEY is not set. Keeping bundled SVG artwork.');
  console.warn('Copy .env.example to .env, add your key, then run `npm run images:fetch`.');
  process.exit(0);
}

function slugify(text) {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const products = [];
for (const file of readdirSync(productsDir).filter((name) => name.endsWith('.ts'))) {
  const source = readFileSync(join(productsDir, file), 'utf8');
  for (const match of source.matchAll(/makeProduct\(\{([\s\S]*?)\}\)/g)) {
    const block = match[1];
    const rawTitle = block.match(/title:\s*'((?:[^'\\]|\\.)*)'/)?.[1];
    const brand = block.match(/brand:\s*'((?:[^'\\]|\\.)*)'/)?.[1] ?? '';
    if (!rawTitle) continue;
    const title = rawTitle.replace(/\\'/g, "'");
    products.push({ slug: slugify(title), title, query: `${brand} ${title}`.trim() });
  }
}

mkdirSync(outputDir, { recursive: true });
const mapping = {};
const credits = [];
const missing = [];
let downloaded = 0;

async function searchPixabay(query, perPage = 4) {
  const url = new URL(API);
  url.searchParams.set('key', apiKey);
  url.searchParams.set('q', query);
  url.searchParams.set('image_type', 'photo');
  url.searchParams.set('orientation', 'square');
  url.searchParams.set('safesearch', 'true');
  url.searchParams.set('per_page', String(perPage));
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Pixabay returned ${response.status} for "${query}"`);
  const data = await response.json();
  return data.hits ?? [];
}

async function saveImage(hit, slug, index) {
  const response = await fetch(hit.largeImageURL ?? hit.webImageURL ?? hit.imageURL);
  if (!response.ok) throw new Error(`Could not download ${hit.id}`);
  const input = Buffer.from(await response.arrayBuffer());
  const output = join(outputDir, `${slug}-${index}.webp`);
  await sharp(input).rotate().resize(1200, 1200, { fit: 'inside', withoutEnlargement: true }).webp({ quality: 82 }).toFile(output);
  return `/images/products/${slug}-${index}.webp`;
}

for (const product of products) {
  try {
    const hits = await searchPixabay(product.query, 4);
    if (hits.length === 0) {
      missing.push(`${product.slug} (no results for "${product.query}")`);
      continue;
    }
    const paths = [];
    for (let index = 0; index < Math.min(2, hits.length); index += 1) {
      paths.push(await saveImage(hits[index], product.slug, index + 1));
      credits.push(`| ${product.slug}-${index + 1}.webp | ${product.title} | [Pixabay #${hits[index].id}](https://pixabay.com/photos/${hits[index].id}/) | ${hits[index].user} | Pixabay Content License |`);
      downloaded += 1;
    }
    mapping[product.slug] = paths;
  } catch (error) {
    missing.push(`${product.slug} (${error instanceof Error ? error.message : String(error)})`);
  }
}

const mapEntries = Object.entries(mapping)
  .map(([slug, paths]) => `  '${slug}': ${JSON.stringify(paths)},`)
  .join('\n');
writeFileSync(
  mapPath,
  `/**
 * Generated by scripts/fetch-images.mjs — do not edit by hand.
 * Maps a product slug to locally hosted Pixabay images.
 * Re-run the script after updating the catalogue.
 */
export const productImageMap: Record<string, string[]> = {
${mapEntries}
};

export function imagesFor(product: { slug: string; images: string[] }): string[] {
  const downloaded = productImageMap[product.slug];
  return downloaded && downloaded.length > 0 ? downloaded : product.images;
}
`,
  'utf8'
);

const header = `# Product image credits

Photos below were downloaded from [Pixabay](https://pixabay.com/) under the
[Pixabay Content License](https://pixabay.com/service/license/). They replace
the bundled SVG demo artwork for mapped products.

| File | Product | Source | Photographer | License |
| --- | --- | --- | --- | --- |
`;
writeFileSync(creditsPath, `${header}${credits.join('\n')}\n`, 'utf8');

console.log(`Downloaded ${downloaded} images for ${Object.keys(mapping).length} products.`);
if (missing.length > 0) {
  console.warn(`Missing images for ${missing.length} products (SVG artwork remains in place):`);
  for (const entry of missing) console.warn(`  - ${entry}`);
} else {
  console.log('All products have downloaded images.');
}
